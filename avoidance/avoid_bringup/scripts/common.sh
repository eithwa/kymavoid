# Shared by avoid_sim.sh / avoid_real.sh / avoid_stop.sh (sourced, not run).
#
# Overridable from the environment:
#   AVOID_WS           catkin workspace (default: found automatically)
#   AVOID_ROS_PORT     roscore port            (11311)
#   AVOID_BRIDGE_PORT  rosbridge websocket     (9090)
#   AVOID_WEB_PORT     web UI http server      (8000)
#   AVOID_GAZEBO_PORT  gzserver master port    (11345, simulation only)
#   AVOID_ROS_IP       ROS_IP for the nodes    (127.0.0.1: everything runs on this machine; the
#                      laptop only talks to rosbridge and the web server, which listen on all
#                      interfaces). Set it to the robot's address to run rviz from another machine.

BRINGUP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
REPO_DIR="$(cd "$BRINGUP_DIR/../.." && pwd -P)"
ROS_PORT="${AVOID_ROS_PORT:-11311}"
BRIDGE_PORT="${AVOID_BRIDGE_PORT:-9090}"
WEB_PORT="${AVOID_WEB_PORT:-8000}"
GAZEBO_PORT="${AVOID_GAZEBO_PORT:-11345}"
MJPEG_PORT=8080

if [ -t 1 ]; then
  C_RED=$'\e[31m'; C_GRN=$'\e[32m'; C_YEL=$'\e[33m'; C_BLD=$'\e[1m'; C_OFF=$'\e[0m'
else
  C_RED=; C_GRN=; C_YEL=; C_BLD=; C_OFF=
fi
info() { echo "${C_GRN}[avoid]${C_OFF} $*"; }
warn() { echo "${C_YEL}[avoid] WARNING:${C_OFF} $*"; }
fail() { echo "${C_RED}[avoid] ERROR:${C_OFF} $*" >&2; exit 1; }

# The catkin workspace whose src/ contains this repository.
find_ws() {
  local cands=() d
  [ -n "$AVOID_WS" ] && cands+=("$AVOID_WS")
  d="$REPO_DIR"
  while [ "$d" != "/" ]; do cands+=("$d"); d="$(dirname "$d")"; done
  cands+=("$HOME/kymavoid_ws" "$HOME/catkin_ws")
  for d in "${cands[@]}"; do
    [ -f "$d/devel/setup.bash" ] && [ -d "$d/src" ] || continue
    local s
    for s in "$d/src" "$d"/src/*; do
      [ "$(realpath -q "$s")" = "$REPO_DIR" ] && { echo "$d"; return 0; }
    done
  done
  return 1
}

# Writes the environment every tmux pane sources, and loads it here too.
# Explicit master URI and ROS_IP: a stale ROS_IP in a terminal once made every node register an
# unreachable address (docs 1, P7).
make_env() {
  local session="$1" ws
  ws="$(find_ws)" || fail "no catkin workspace with this repository in src/ and a devel/ (set AVOID_WS, or run catkin_make)"
  RUN_DIR="${XDG_RUNTIME_DIR:-/tmp}/avoid_bringup/$session"
  mkdir -p "$RUN_DIR"
  ENV_FILE="$RUN_DIR/env.sh"
  cat > "$ENV_FILE" <<EOF
# generated by avoid_bringup/scripts/common.sh
source /opt/ros/noetic/setup.bash
source "$ws/devel/setup.bash"
export ROS_MASTER_URI=http://localhost:$ROS_PORT
unset ROS_HOSTNAME
export ROS_IP=${AVOID_ROS_IP:-127.0.0.1}
export GAZEBO_MASTER_URI=http://localhost:$GAZEBO_PORT
export AVOID_SESSION=$session
# scripts run from a pane (avoid_stop.sh) must address this instance, not the default-port one
export AVOID_ROS_PORT=$ROS_PORT AVOID_BRIDGE_PORT=$BRIDGE_PORT AVOID_WEB_PORT=$WEB_PORT AVOID_GAZEBO_PORT=$GAZEBO_PORT
export PYTHONUNBUFFERED=1
EOF
  # shellcheck disable=SC1090
  source "$ENV_FILE"
  info "workspace $ws, ROS_MASTER_URI=$ROS_MASTER_URI, ROS_IP=$ROS_IP"
}

# One instance per ROS master port. Its tmux session, its process marker (AVOID_SESSION) and its
# environment file all carry this name, so instances on other ports (a test copy next to a running
# simulation) never touch each other: avoid_sim on the default port, avoid_sim-11313 on 11313.
instance() { if [ "$ROS_PORT" = 11311 ]; then echo "$1"; else echo "$1-$ROS_PORT"; fi; }

port_busy() { ss -Hltn "sport = :$1" 2>/dev/null | grep -q .; }

check_ports() {
  local p bad=0
  for p in "$@"; do
    if port_busy "$p"; then
      echo "${C_RED}[avoid] port $p is in use:${C_OFF}"
      ss -Hltnp "sport = :$p" 2>/dev/null | sed 's/^/    /'
      bad=1
    fi
  done
  [ $bad = 0 ] || fail "stop whatever uses these ports first (a leftover roscore / roslaunch / gzserver?): scripts/avoid_stop.sh, or 'killall -INT roslaunch rosmaster gzserver'"
}

check_pkgs() {
  local p missing=()
  for p in "$@"; do rospack find "$p" >/dev/null 2>&1 || missing+=("$p"); done
  [ ${#missing[@]} = 0 ] || fail "ROS packages not found: ${missing[*]} (not built, or not installed: sudo apt install ros-noetic-<name>)"
}

# Git-ignored config files that the robot code expects: copy them from the "(default)" templates.
ensure_config() {
  local f dir base ext def
  for f in "$@"; do
    [ -f "$f" ] && continue
    dir="$(dirname "$f")"; base="$(basename "$f")"; ext="${base##*.}"
    def="$dir/${base%.*} (default).$ext"
    [ -f "$def" ] || fail "missing $f and no template '$def'"
    cp "$def" "$f"
    info "created $f from its (default) template"
  done
}

wait_master() {
  local i
  for i in $(seq 1 "${1:-20}"); do
    rosparam get /run_id >/dev/null 2>&1 && return 0
    sleep 1
  done
  fail "roscore did not come up on $ROS_MASTER_URI (see tmux window 'core')"
}

wait_param() {
  local i
  for i in $(seq 1 "${2:-60}"); do
    rosparam get "$1" >/dev/null 2>&1 && return 0
    sleep 1
  done
  warn "parameter $1 did not appear in ${2:-60} s; starting the next window anyway"
}

# Processes started from a session carry AVOID_SESSION=<session> in their environment. tmux
# itself never does (see tmux() below): it may be the user's server with other sessions in it.
session_pids() {
  local p comm
  for p in /proc/[0-9]*; do
    [ "${p#/proc/}" = "$$" ] && continue
    grep -qsz "^AVOID_SESSION=$1\$" "$p/environ" || continue
    read -r comm < "$p/comm" 2>/dev/null
    case "$comm" in tmux*) continue ;; esac
    echo "${p#/proc/}"
  done
}

# The tmux server must not inherit the session marker (a new server would, as a child of this
# script after make_env).
tmux() { env -u AVOID_SESSION tmux "$@"; }

# tmux window running a command in the session environment; the shell stays when it exits
# (press up + enter to restart it).
tmux_window() {
  local session="$1" name="$2" cmd="$3"
  if tmux has-session -t "$session" 2>/dev/null; then
    tmux new-window -d -t "$session:" -n "$name"
  else
    tmux new-session -d -s "$session" -n "$name" -x 220 -y 50
  fi
  tmux send-keys -t "$session:$name" "source '$ENV_FILE'; $cmd" C-m
}

lan_urls() {
  local ip
  for ip in $(hostname -I 2>/dev/null) 127.0.0.1; do
    case "$ip" in *:*) continue ;; esac
    if [ "$BRIDGE_PORT" = 9090 ]; then echo "    http://$ip:$WEB_PORT/"
    else echo "    http://$ip:$WEB_PORT/?bridge=ws://$ip:$BRIDGE_PORT"; fi
  done
}

# Starts the windows shared by both versions; $1 session, $2 core launch command, $3 sensor.
start_session() {
  local session="$1" core="$2" sensor="$3"
  tmux_window "$session" core "roscore -p $ROS_PORT"
  wait_master 20
  tmux split-window -v -p 80 -t "$session:core" -c "$BRINGUP_DIR"    # new pane becomes the active one
  tmux send-keys -t "$session:core" "source '$ENV_FILE'; $core" C-m
  # nav_node starts after the core launch has set its parameters (use_sim_time in the simulation)
  wait_param /robot_description 60
  tmux_window "$session" nav "roslaunch avoid_nav nav.launch sensor:=$sensor"
  tmux_window "$session" web "rosrun avoid_bringup web_server.py $WEB_PORT"
  tmux_window "$session" monitor "rosrun avoid_bringup monitor.py"
  tmux_window "$session" shell "clear; echo 'avoid: $session ($sensor)   stop everything: $BRINGUP_DIR/scripts/avoid_stop.sh'; echo 'rosservice call /avoid/command start|stop|reset|save'"
  tmux select-window -t "$session:monitor"
  echo
  info "${C_BLD}tmux session '$session' is up${C_OFF} (windows: core nav web monitor shell)"
  info "web UI:"
  lan_urls
  local envp=""
  [ "$ROS_PORT" = 11311 ] || envp="AVOID_ROS_PORT=$ROS_PORT "
  info "attach: tmux attach -t $session      stop: $envp$BRINGUP_DIR/scripts/avoid_stop.sh"
}

attach_session() {
  [ "$NO_ATTACH" = 1 ] && return 0
  [ -t 0 ] || return 0
  if [ -n "$TMUX" ]; then tmux switch-client -t "$1"; else exec tmux attach -t "$1"; fi
}
